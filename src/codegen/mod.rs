        writeln!(self.output, "                return ok;").unwrap();
        writeln!(self.output, "            }}").unwrap();
        writeln!(self.output, "            if (ch->closed) {{ pthread_mutex_unlock(&ch->mu); return 0; }}").unwrap();
        writeln!(self.output, "            pthread_cond_wait(&ch->not_full, &ch->mu);").unwrap();
        writeln!(self.output, "        }}").unwrap();
        writeln!(self.output, "    }}").unwrap();
        writeln!(self.output, "    while (ch->len == ch->cap && !ch->closed) pthread_cond_wait(&ch->not_full, &ch->mu);").unwrap();
        writeln!(self.output, "    if (ch->closed) {{ pthread_mutex_unlock(&ch->mu); return 0; }}").unwrap();
        writeln!(self.output, "    ch->buf[(ch->head + ch->len) % ch->cap] = p;").unwrap();
        writeln!(self.output, "    ch->len++;").unwrap();
        writeln!(self.output, "    pthread_cond_signal(&ch->not_empty);").unwrap();
        writeln!(self.output, "    pthread_mutex_unlock(&ch->mu);").unwrap();
        writeln!(self.output, "    return 1;").unwrap();
        writeln!(self.output, "}}").unwrap();
        writeln!(self.output, "void* glyph_channel_recv(void* cp) {{").unwrap();
        writeln!(self.output, "    GlyphChannel* ch = (GlyphChannel*)cp;").unwrap();
        writeln!(self.output, "    pthread_mutex_lock(&ch->mu);").unwrap();
        writeln!(self.output, "    if (ch->cap <= 0) {{").unwrap();
        writeln!(self.output, "        for (;;) {{").unwrap();
        writeln!(self.output, "            if (ch->has_slot) break;").unwrap();
        writeln!(self.output, "            if (ch->closed) {{ pthread_mutex_unlock(&ch->mu); return NULL; }}").unwrap();
        writeln!(self.output, "            ch->receiver_waiting++;").unwrap();
        writeln!(self.output, "            pthread_cond_signal(&ch->not_full);").unwrap();
        writeln!(self.output, "            pthread_cond_wait(&ch->not_empty, &ch->mu);").unwrap();
        writeln!(self.output, "            ch->receiver_waiting--;").unwrap();
        writeln!(self.output, "        }}").unwrap();
        writeln!(self.output, "        void* p = ch->slot;").unwrap();
        writeln!(self.output, "        ch->has_slot = 0; ch->taken = 1;").unwrap();
        writeln!(self.output, "        pthread_cond_signal(&ch->not_full);").unwrap();
        writeln!(self.output, "        pthread_mutex_unlock(&ch->mu);").unwrap();
        writeln!(self.output, "        return p;").unwrap();
        writeln!(self.output, "    }}").unwrap();
        writeln!(self.output, "    while (ch->len == 0 && !ch->closed) pthread_cond_wait(&ch->not_empty, &ch->mu);").unwrap();
        writeln!(self.output, "    if (ch->len == 0) {{ pthread_mutex_unlock(&ch->mu); return NULL; }}").unwrap();
        writeln!(self.output, "    void* p = ch->buf[ch->head];").unwrap();
        writeln!(self.output, "    ch->head = (ch->head + 1) % ch->cap;").unwrap();
        writeln!(self.output, "    ch->len--;").unwrap();
        writeln!(self.output, "    pthread_cond_signal(&ch->not_full);").unwrap();
        writeln!(self.output, "    pthread_mutex_unlock(&ch->mu);").unwrap();
        writeln!(self.output, "    return p;").unwrap();
        writeln!(self.output, "}}").unwrap();
        writeln!(self.output, "void glyph_channel_close(void* cp) {{").unwrap();
        writeln!(self.output, "    GlyphChannel* ch = (GlyphChannel*)cp;").unwrap();
        writeln!(self.output, "    pthread_mutex_lock(&ch->mu);").unwrap();
        writeln!(self.output, "    ch->closed = 1;").unwrap();
        writeln!(self.output, "    pthread_cond_broadcast(&ch->not_full);").unwrap();
        writeln!(self.output, "    pthread_cond_broadcast(&ch->not_empty);").unwrap();
        writeln!(self.output, "    pthread_mutex_unlock(&ch->mu);").unwrap();
        writeln!(self.output, "}}").unwrap();
        writeln!(self.output, "").unwrap();

        // Math functions (use <math.h>)
        writeln!(self.output, "double glyph_abs(double x) {{ return x < 0 ? -x : x; }}").unwrap();
        writeln!(self.output, "double glyph_min(double a, double b) {{ return a < b ? a : b; }}").unwrap();
        writeln!(self.output, "double glyph_max(double a, double b) {{ return a > b ? a : b; }}").unwrap();
        writeln!(self.output, "double glyph_sqrt(double x) {{ return sqrt(x); }}").unwrap();
        writeln!(self.output, "double glyph_pow(double b, double e) {{ return pow(b, e); }}").unwrap();
        writeln!(self.output, "double glyph_floor(double x) {{ return floor(x); }}").unwrap();
        writeln!(self.output, "double glyph_ceil(double x) {{ return ceil(x); }}").unwrap();
        writeln!(self.output, "double glyph_round(double x) {{ return round(x); }}").unwrap();
        writeln!(self.output, "double glyph_log(double x) {{ return log(x); }}").unwrap();
        writeln!(self.output, "double glyph_log2(double x) {{ return log2(x); }}").unwrap();
        writeln!(self.output, "double glyph_log10(double x) {{ return log10(x); }}").unwrap();
        writeln!(self.output, "double glyph_sin(double x) {{ return sin(x); }}").unwrap();
        writeln!(self.output, "double glyph_cos(double x) {{ return cos(x); }}").unwrap();
        writeln!(self.output, "double glyph_tan(double x) {{ return tan(x); }}").unwrap();
        writeln!(self.output, "").unwrap();

        // File I/O
        writeln!(self.output, "").unwrap();
        writeln!(self.output, "char* glyph_file_read(const char* path) {{").unwrap();
        writeln!(self.output, "    FILE* f = fopen(path, \"rb\");").unwrap();
        writeln!(self.output, "    if (!f) return strdup(\"\");").unwrap();
        writeln!(self.output, "    fseek(f, 0, SEEK_END); long sz = ftell(f); fseek(f, 0, SEEK_SET);").unwrap();
        writeln!(self.output, "    char* buf = (char*)malloc(sz + 1); fread(buf, 1, sz, f); buf[sz] = 0; fclose(f);").unwrap();
        writeln!(self.output, "    return buf;").unwrap();
        writeln!(self.output, "}}").unwrap();
        writeln!(self.output, "int glyph_file_write(const char* path, const char* content) {{").unwrap();
        writeln!(self.output, "    FILE* f = fopen(path, \"wb\"); if (!f) return 0;").unwrap();
        writeln!(self.output, "    fwrite(content, 1, strlen(content), f); fclose(f); return 1;").unwrap();
        writeln!(self.output, "}}").unwrap();
        writeln!(self.output, "int glyph_file_append(const char* path, const char* content) {{").unwrap();
        writeln!(self.output, "    FILE* f = fopen(path, \"ab\"); if (!f) return 0;").unwrap();
        writeln!(self.output, "    fwrite(content, 1, strlen(content), f); fclose(f); return 1;").unwrap();
        writeln!(self.output, "}}").unwrap();
        writeln!(self.output, "int glyph_file_exists(const char* path) {{").unwrap();
        writeln!(self.output, "    FILE* f = fopen(path, \"r\"); if (f) {{ fclose(f); return 1; }} return 0;").unwrap();
        writeln!(self.output, "}}").unwrap();
        writeln!(self.output, "int glyph_create_dir(const char* path) {{").unwrap();
        writeln!(self.output, "    #ifdef _WIN32").unwrap();
        writeln!(self.output, "    return _mkdir(path) == 0;").unwrap();
        writeln!(self.output, "    #else").unwrap();
        writeln!(self.output, "    return mkdir(path, 0755) == 0;").unwrap();
        writeln!(self.output, "    #endif").unwrap();
        writeln!(self.output, "}}").unwrap();
        writeln!(self.output, "int glyph_remove_file(const char* path) {{ return remove(path) == 0; }}").unwrap();
        writeln!(self.output, "").unwrap();

        // Assert
        writeln!(self.output, "static void glyph_test_fail(const char* msg) {{").unwrap();
        writeln!(self.output, "    if (_glyph_test_active) {{").unwrap();
        writeln!(self.output, "        fprintf(stderr, \"%s\\n\", msg);").unwrap();
        writeln!(self.output, "        longjmp(_glyph_test_jmp, 1);").unwrap();
        writeln!(self.output, "    }} else {{").unwrap();
        writeln!(self.output, "        fprintf(stderr, \"Assertion failed: %s\\n\", msg);").unwrap();
        writeln!(self.output, "        abort();").unwrap();
        writeln!(self.output, "    }}").unwrap();
        writeln!(self.output, "}}").unwrap();
        writeln!(self.output, "void glyph_assert(int cond, const char* msg) {{ if (!cond) glyph_test_fail(msg); }}").unwrap();
        writeln!(self.output, "void glyph_assert_true(int v, const char* msg) {{ if (!v) glyph_test_fail(msg); }}").unwrap();
        writeln!(self.output, "void glyph_assert_false(int v, const char* msg) {{ if (v) glyph_test_fail(msg); }}").unwrap();
        writeln!(self.output, "void glyph_assert_eq_i64(int64_t a, int64_t b, const char* msg) {{").unwrap();
        writeln!(self.output, "    if (a != b) {{ char buf[512]; snprintf(buf, sizeof buf, \"%s: expected %lld, got %lld\", msg, (long long)b, (long long)a); glyph_test_fail(buf); }}").unwrap();
        writeln!(self.output, "}}").unwrap();
        writeln!(self.output, "void glyph_assert_eq_u64(uint64_t a, uint64_t b, const char* msg) {{").unwrap();
        writeln!(self.output, "    if (a != b) {{ char buf[512]; snprintf(buf, sizeof buf, \"%s: expected %llu, got %llu\", msg, (unsigned long long)b, (unsigned long long)a); glyph_test_fail(buf); }}").unwrap();
        writeln!(self.output, "}}").unwrap();
        writeln!(self.output, "void glyph_assert_eq_f64(double a, double b, const char* msg) {{").unwrap();
        writeln!(self.output, "    if (a != b) {{ char buf[512]; snprintf(buf, sizeof buf, \"%s: expected %f, got %f\", msg, b, a); glyph_test_fail(buf); }}").unwrap();
        writeln!(self.output, "}}").unwrap();
        writeln!(self.output, "void glyph_assert_eq_str(const char* a, const char* b, const char* msg) {{").unwrap();
